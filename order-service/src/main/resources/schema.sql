CREATE TABLE IF NOT EXISTS order_inbox(event_id UUID PRIMARY KEY, received_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS order_sagas(order_id UUID PRIMARY KEY, state VARCHAR(30) NOT NULL, reason TEXT, updated_at TIMESTAMPTZ NOT NULL DEFAULT now());

CREATE TABLE IF NOT EXISTS documents(kind VARCHAR(30) NOT NULL,id UUID NOT NULL,owner_id UUID NOT NULL,payload TEXT NOT NULL,PRIMARY KEY(kind,id));
