CREATE TABLE IF NOT EXISTS products (
 id UUID PRIMARY KEY, title VARCHAR(200) NOT NULL,
 price NUMERIC(19,2) NOT NULL CHECK(price >= 0), currency VARCHAR(3) NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity >= 0)
);

CREATE TABLE IF NOT EXISTS inbox_events(event_id UUID PRIMARY KEY, received_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS inventory_outbox(event_id UUID PRIMARY KEY, order_id UUID NOT NULL, payload TEXT NOT NULL, sent BOOLEAN NOT NULL DEFAULT false, created_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS reservations(order_id UUID PRIMARY KEY, customer_id UUID NOT NULL, state VARCHAR(20) NOT NULL, items TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS wallets(customer_id UUID PRIMARY KEY, currency VARCHAR(3) NOT NULL, balance NUMERIC(19,2) NOT NULL CHECK(balance>=0));
CREATE TABLE IF NOT EXISTS payments(order_id UUID PRIMARY KEY, customer_id UUID NOT NULL, amount NUMERIC(19,2) NOT NULL CHECK(amount>=0), currency VARCHAR(3) NOT NULL, state VARCHAR(20) NOT NULL);

CREATE TABLE IF NOT EXISTS documents(kind VARCHAR(30) NOT NULL,id UUID NOT NULL,owner_id UUID NOT NULL,payload TEXT NOT NULL,PRIMARY KEY(kind,id));
